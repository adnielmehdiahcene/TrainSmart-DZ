def extraire_donnees_robuste(uploaded_file):
    raw_bytes = uploaded_file.getvalue().replace(b'\x00', b'')
    text = raw_bytes.decode('utf-8-sig', errors='ignore')
    text_fixed = re.sub(r'"[^"]*"', lambda m: m.group(0).replace('\n', ' ').replace('\r', ''), text)
    lines = text_fixed.splitlines()
    h_idx = next((i for i, l in enumerate(lines[:20]) if any(kw in l for kw in ["Durée", "Distance", "Circuits"])), 0)
    data_io = io.StringIO("\n".join(lines[h_idx:]))
    df = pd.DataFrame(list(csv.reader(data_io, delimiter=',', quotechar='"')))
    df.columns = df.iloc[0]
    df = df[1:].copy()
    df.columns = [re.sub(r'\s+', ' ', str(c)).strip() for c in df.columns]
    for col in df.columns:
        df[col] = df[col].apply(lambda x: str(x).replace(',', '.') if isinstance(x, str) else x)
    return df

