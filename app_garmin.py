def smart_parse_time(val):
    try:
        p = str(val).split(':')
        if len(p) == 2: return int(p[0])*60 + float(p[1])
        if len(p) == 3: return int(p[0])*3600 + int(p[1])*60 + float(p[2])
        return float(val)
    except: return 0.0

